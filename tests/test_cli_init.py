"""Regression: `aipr init` must work from the installed console script.

main() only reached its init fast-path when argv was passed explicitly
(e.g. main(["init", "--dir", "."])), so the console script generated by
setuptools — which calls main() with no arguments and therefore
argv=None — fell through to argparse, which rejected --dir and never
created the policy files. See yunaremaia/aipr issue #7.
"""

import os
import subprocess
import sys
from pathlib import Path


def test_init_from_console_script_creates_policy_files(tmp_path):
    """The installed console script must scaffold AI_POLICY.md in --dir."""
    target = tmp_path / "scaffold"
    target.mkdir()

    result = subprocess.run(
        ["aipr", "init", "--dir", str(target)],
        capture_output=True,
        text=True,
        env={**os.environ, "PATH": f"{os.path.dirname(sys.executable)}:{os.environ.get('PATH', '')}"},
    )

    assert result.returncode == 0, result.stderr
    policy = target / "AI_POLICY.md"
    assert policy.exists(), f"AI_POLICY.md not created. stdout={result.stdout!r} stderr={result.stderr!r}"
    assert "AI Usage Policy" in policy.read_text()
    assert (target / "AI_TOOL_POLICY.md").exists()


def test_main_with_none_argv_reaches_init_fast_path(tmp_path, monkeypatch):
    """main(argv=None) — what the console script passes — must see sys.argv[1:]."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(sys, "argv", ["aipr", "init", "--dir", str(tmp_path)])

    from aipr.cli import main

    assert main() == 0
    assert (tmp_path / "AI_POLICY.md").exists()


def test_gh_aipr_wrapper_init_creates_policy_files(tmp_path):
    """The gh extension wrapper also calls main() with no args (issue #7 sibling)."""
    wrapper = Path(__file__).parent.parent / "gh-aipr"
    result = subprocess.run(
        [sys.executable, str(wrapper), "init", "--dir", str(tmp_path)],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    assert (tmp_path / "AI_POLICY.md").exists()
